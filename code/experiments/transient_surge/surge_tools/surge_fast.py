"""Compiled (Numba) engine for the surge experiment, with the dispatch rules of simulation_fast.py.

Drop-in for surge_simulation.simulation / simulation_batch_run: same arguments, same schedule (make_surge_schedule),
same bins, reports and recovery rule (measure_recovery), same result keys -- plus backorders when base-stock levels
are given (stocks=...), which the Python engine does not compute.

Model and rules (as simulation_fast.py, i.e. as Section 4.3 of the paper; they differ from surge_simulation.py in
the first two points):
  - an arriving part goes to the qualified idle technician that has been idle longest (Python engine: lowest index);
  - if none is idle, the qualified technician repairing the lowest-priority part of strictly lower priority is
    interrupted (ties: the most recently failed part; Python engine: incoming score, then technician index); the
    interrupted part returns to the head of its queue and is dispatched again by the same rule (cascade);
  - a technician that finishes takes the waiting part of highest priority it is qualified for (ties: earliest failure);
  - an interrupted repair draws a fresh exponential time when restarted (= resume in distribution for exponential
    repair times; the Python engine keeps the remaining work);
  - priorities: lower value = higher priority; equal values = FCFS across SKUs.
Failures: Poisson with rate Lambda * m(t), m = surgeMultiplier during the surge phase and 1 otherwise, generated by
inverting the integrated intensity; with surgeMultiplier = 1 the random-number stream is draw for draw the one of
simulation_fast.simulate (used as a verification check).

Seeds: replication i of a batch uses the integer seed startSeed + 20 i (Numba's generator), as in simulation_fast.
Waiting-time statistics are not collected (the "waiting" entries are None).
"""
from __future__ import annotations

import numpy as np
from numba import njit

from . import surge_simulation as ss

_INF = np.inf


@njit(cache=True)
def _advance(t0, t1, b, edges, bin_phase, warm_end, count, qlen, S, use_S, busy_k,
             bin_q, bin_sys, bin_bo, phase_q, phase_sys, phase_bo, phase_busy, phase_dur, dist, over, maxq):
    """Integrate the piecewise-constant state over [t0, t1); returns the updated bin index."""
    N = count.shape[0]
    M = busy_k.shape[0]
    nb = edges.shape[0] - 1
    while t0 < t1:
        if t0 < warm_end:
            end = t1 if t1 < warm_end else warm_end
            p = 0
        else:
            end = t1 if t1 < edges[b + 1] else edges[b + 1]
            p = bin_phase[b]
        d = end - t0
        phase_dur[p] += d
        for k in range(N):
            c = count[k]
            q = qlen[k]
            bo = c - S[k] if use_S and c > S[k] else 0
            phase_q[p, k] += d * q
            phase_sys[p, k] += d * c
            phase_bo[p, k] += d * bo
            if p > 0:
                bin_q[b, k] += d * q
                bin_sys[b, k] += d * c
                bin_bo[b, k] += d * bo
                if c < maxq:
                    dist[k, c] += d
                else:
                    over[k] += d
        for j in range(M):
            if busy_k[j] >= 0:
                phase_busy[p, j, busy_k[j]] += d
        t0 = end
        if p > 0 and end == edges[b + 1] and b < nb - 1:
            b += 1
    return b


@njit(cache=True)
def _next_arrival(t, Lam, gamma, ts, te):
    """Next failure time of a Poisson process with rate Lam, times gamma on [ts, te)."""
    if gamma == 1.0:
        return t + np.random.exponential(1.0 / Lam)
    r = np.random.exponential(1.0)
    if t < ts:
        a = Lam * (ts - t)
        if r < a:
            return t + r / Lam
        r -= a
        t = ts
    if t < te:
        a = Lam * gamma * (te - t)
        if r < a:
            return t + r / (Lam * gamma)
        r -= a
        t = te
    return t + r / Lam


@njit(cache=True)
def _start(j, k, t, R, qa, qf, qp, qhead, qlen, cap, busy_k, busy_a, busy_p, busy_since, comp, starts):
    h = qhead[k]
    busy_a[j] = qa[k, h]
    busy_p[j] = qp[k, h]
    qhead[k] = (h + 1) % cap
    qlen[k] -= 1
    busy_k[j] = k
    busy_since[j] = t
    comp[j] = t + np.random.exponential(1.0 / R[j, k])
    starts[j, k] += 1.0


@njit(cache=True)
def _run_surge(lam, R, score, edges, bin_phase, phase_edges, gamma, S, use_S, seed, maxq, cap, abs_j, abs_t0, abs_t1,
               score2, pre_base, pre2, sw_t0, sw_t1):
    np.random.seed(seed)
    N = lam.shape[0]
    M = R.shape[0]
    nb = edges.shape[0] - 1
    Lam = lam.sum()
    cum = np.cumsum(lam / Lam)
    warm_end = phase_edges[1]
    ts = phase_edges[2]
    te = phase_edges[3]
    stop = phase_edges[4]
    qa = np.empty((N, cap))
    qf = np.zeros((N, cap), np.int8)
    qp = np.zeros((N, cap), np.int8)
    qhead = np.zeros(N, np.int64)
    qlen = np.zeros(N, np.int64)
    count = np.zeros(N, np.int64)
    busy_k = -np.ones(M, np.int64)
    busy_a = np.zeros(M)
    busy_p = np.zeros(M, np.int8)
    busy_since = np.zeros(M)
    comp = np.full(M, _INF)
    idle_since = np.zeros(M)
    starts = np.zeros((M, N))
    bin_q = np.zeros((nb, N))
    bin_sys = np.zeros((nb, N))
    bin_bo = np.zeros((nb, N))
    bin_arr = np.zeros((nb, N), np.int64)
    bin_dep = np.zeros((nb, N), np.int64)
    phase_q = np.zeros((4, N))
    phase_sys = np.zeros((4, N))
    phase_bo = np.zeros((4, N))
    phase_busy = np.zeros((4, M, N))
    phase_dur = np.zeros(4)
    phase_peak_q = np.zeros(4, np.int64)
    phase_peak_bo = np.zeros(4, np.int64)
    arrivals = np.zeros((4, N), np.int64)
    departures = np.zeros((4, N), np.int64)
    completed = np.zeros((4, N), np.int64)      # by ARRIVAL phase of the completed part
    comp_post = np.zeros((M, N))                # completions after warm-up, by technician and SKU
    dist = np.zeros((N, maxq))
    over = np.zeros(N)
    overflow_queue = False
    n_events = 0
    n_preempt = 0

    b = 0
    t = 0.0
    absent = False
    abs_pending = abs_j >= 0
    n_absence_events = 0
    next_arr = _next_arrival(0.0, Lam, gamma, ts, te)
    scm = score
    pre = pre_base
    while True:
        jmin = -1
        tc = _INF
        for j in range(M):
            if comp[j] < tc:
                tc = comp[j]
                jmin = j
        t_next = next_arr if next_arr <= tc else tc
        kind = 0 if next_arr <= tc else 1                              # 0 arrival, 1 completion, 2 absence starts, 3 absence ends
        if abs_pending and abs_t0 < t_next:
            t_next = abs_t0
            kind = 2
        elif absent and abs_t1 < t_next:
            t_next = abs_t1
            kind = 3
        if t_next >= stop:
            break
        b = _advance(t, t_next, b, edges, bin_phase, warm_end, count, qlen, S, use_S, busy_k,
                     bin_q, bin_sys, bin_bo, phase_q, phase_sys, phase_bo, phase_busy, phase_dur, dist, over, maxq)
        t = t_next
        if t < warm_end:
            p = 0
        else:
            p = bin_phase[b]
            if t >= edges[b + 1] and b < nb - 1:          # exactly on a bin edge: the event belongs to the next bin
                b += 1
                p = bin_phase[b]
        n_events += 1
        if t >= sw_t0 and t < sw_t1:                                  # rule switched for the disruption
            scm = score2
            pre = pre2
        else:
            scm = score
            pre = pre_base
        if kind == 2:                                                 # ---------------- technician leaves
            abs_pending = False
            absent = True
            n_absence_events += 1
            if busy_k[abs_j] >= 0:                                    # the repair in progress goes back to the head of its queue
                v = busy_k[abs_j]
                h = (qhead[v] - 1) % cap
                qhead[v] = h
                qa[v, h] = busy_a[abs_j]
                qf[v, h] = 1
                qp[v, h] = busy_p[abs_j]
                qlen[v] += 1
                busy_k[abs_j] = -1
                comp[abs_j] = _INF
                n_preempt += 1
                kk = v                                                # the part looks for another technician (same rule as a preemption)
                while kk >= 0:
                    jbest = -1
                    best_idle = _INF
                    for j in range(M):
                        if R[j, kk] > 0.0 and busy_k[j] < 0 and idle_since[j] < best_idle and j != abs_j:
                            best_idle = idle_since[j]
                            jbest = j
                    if jbest >= 0:
                        _start(jbest, kk, t, R, qa, qf, qp, qhead, qlen, cap, busy_k, busy_a, busy_p, busy_since, comp, starts)
                        break
                    if not pre:                                           # non-preemptive: no interruption
                        break
                    jv = -1
                    vs = -_INF
                    va = -_INF
                    for j in range(M):
                        if R[j, kk] > 0.0 and busy_k[j] >= 0 and j != abs_j:
                            cs = scm[j, busy_k[j]]
                            if scm[j, kk] < cs and (cs > vs or (cs == vs and busy_a[j] > va)):
                                jv = j
                                vs = cs
                                va = busy_a[j]
                    if jv < 0:
                        break
                    v2 = busy_k[jv]
                    h2 = (qhead[v2] - 1) % cap
                    qhead[v2] = h2
                    qa[v2, h2] = busy_a[jv]
                    qf[v2, h2] = 1
                    qp[v2, h2] = busy_p[jv]
                    qlen[v2] += 1
                    busy_k[jv] = -1
                    comp[jv] = _INF
                    n_preempt += 1
                    _start(jv, kk, t, R, qa, qf, qp, qhead, qlen, cap, busy_k, busy_a, busy_p, busy_since, comp, starts)
                    kk = v2
        elif kind == 3:                                               # ---------------- technician returns, takes the best waiting part
            absent = False
            n_absence_events += 1
            idle_since[abs_j] = t
            best = -1
            bs = _INF
            ba = _INF
            for kk in range(N):
                if R[abs_j, kk] > 0.0 and qlen[kk] > 0:
                    sc = scm[abs_j, kk]
                    a = qa[kk, qhead[kk]]
                    if sc < bs or (sc == bs and a < ba):
                        best = kk
                        bs = sc
                        ba = a
            if best >= 0:
                _start(abs_j, best, t, R, qa, qf, qp, qhead, qlen, cap, busy_k, busy_a, busy_p, busy_since, comp, starts)
        elif kind == 0:                                               # ---------------- arrival
            u = np.random.random()
            k = 0
            while k < N - 1 and cum[k] <= u:
                k += 1
            count[k] += 1
            arrivals[p, k] += 1
            if p > 0:
                bin_arr[b, k] += 1
            if qlen[k] >= cap:
                overflow_queue = True
                break
            idx = (qhead[k] + qlen[k]) % cap
            qa[k, idx] = t
            qf[k, idx] = 0
            qp[k, idx] = p
            qlen[k] += 1
            kk = k
            while kk >= 0:                                            # dispatch, with cascade
                jbest = -1
                best_idle = _INF
                for j in range(M):
                    if R[j, kk] > 0.0 and busy_k[j] < 0 and idle_since[j] < best_idle and not (absent and j == abs_j):
                        best_idle = idle_since[j]
                        jbest = j
                if jbest >= 0:
                    _start(jbest, kk, t, R, qa, qf, qp, qhead, qlen, cap, busy_k, busy_a, busy_p, busy_since, comp, starts)
                    break
                if not pre:                                           # non-preemptive: no interruption
                    break
                jv = -1
                vs = -_INF
                va = -_INF
                for j in range(M):
                    if R[j, kk] > 0.0 and busy_k[j] >= 0:
                        cs = scm[j, busy_k[j]]
                        if scm[j, kk] < cs and (cs > vs or (cs == vs and busy_a[j] > va)):
                            jv = j
                            vs = cs
                            va = busy_a[j]
                if jv < 0:
                    break
                v = busy_k[jv]
                h = (qhead[v] - 1) % cap                             # interrupted part back to the head of its queue
                qhead[v] = h
                qa[v, h] = busy_a[jv]
                qf[v, h] = 1
                qp[v, h] = busy_p[jv]
                qlen[v] += 1
                busy_k[jv] = -1
                comp[jv] = _INF
                n_preempt += 1
                _start(jv, kk, t, R, qa, qf, qp, qhead, qlen, cap, busy_k, busy_a, busy_p, busy_since, comp, starts)
                kk = v                                                # the interrupted part looks for a technician
            next_arr = _next_arrival(t, Lam, gamma, ts, te)
        else:                                                         # ---------------- completion
            j = jmin
            k = busy_k[j]
            count[k] -= 1
            departures[p, k] += 1
            completed[busy_p[j], k] += 1
            if p > 0:
                bin_dep[b, k] += 1
                comp_post[j, k] += 1.0
            busy_k[j] = -1
            comp[j] = _INF
            idle_since[j] = t
            best = -1
            bs = _INF
            ba = _INF
            for kk in range(N):
                if R[j, kk] > 0.0 and qlen[kk] > 0:
                    s = scm[j, kk]
                    a = qa[kk, qhead[kk]]
                    if s < bs or (s == bs and a < ba):
                        best = kk
                        bs = s
                        ba = a
            if best >= 0:
                _start(j, best, t, R, qa, qf, qp, qhead, qlen, cap, busy_k, busy_a, busy_p, busy_since, comp, starts)
        qt = 0
        bt = 0
        for k2 in range(N):                                           # peaks, evaluated after every event
            qt += qlen[k2]
            if use_S and count[k2] > S[k2]:
                bt += count[k2] - S[k2]
        if qt > phase_peak_q[p]:
            phase_peak_q[p] = qt
        if bt > phase_peak_bo[p]:
            phase_peak_bo[p] = bt
    if not overflow_queue:
        b = _advance(t, stop, b, edges, bin_phase, warm_end, count, qlen, S, use_S, busy_k,
                     bin_q, bin_sys, bin_bo, phase_q, phase_sys, phase_bo, phase_busy, phase_dur, dist, over, maxq)
    in_service = np.zeros(N, np.int64)
    for j in range(M):
        if busy_k[j] >= 0:
            in_service[busy_k[j]] += 1
    return (bin_q, bin_sys, bin_bo, bin_arr, bin_dep, phase_q, phase_sys, phase_bo, phase_busy, phase_dur,
            phase_peak_q, phase_peak_bo, arrivals, departures, completed, comp_post, dist, over, count, qlen,
            in_service, overflow_queue, n_events, n_preempt, n_absence_events)


def simulation(
    requestArrivalRate=5.0, skillDistribution=None, skillServerRates=None, skillServerCosts=None,
    histogramBucketsInput=(0.0,), expectedTotalNumberRequests=100_000, numberWarmingUpRequests=10_000, seed=10,
    collectWaitingTimeStatisticsInput=False, *,
    numberBaselineRequests=20_000, numberSurgeRequests=10_000, surgeMultiplier=3.0, sampleEveryArrivals=100.0,
    queueReportEveryArrivals=10_000.0, recoveryAbsTolerance=1.0, recoveryRelTolerance=0.10,
    recoveryHoldArrivals=1_000.0, maxQueue=500, preemptive=True, stocks=None, absence=None, switch=None,
):
    """One replication; the arguments and result keys of surge_simulation.simulation (seed: an integer).

    absence: (technician j, start, end) with start and end in EXPECTED FAILURES from the beginning of the run
    (converted to physical time with the base rate): technician j takes no part on [start, end); its repair in progress
    at `start` goes back to the head of its queue and is dispatched again by the usual rule; at `end` the technician
    returns and takes the best waiting part. A technician-loss disruption (B5); None = no absence.

    stocks: base-stock levels S [N] (optional). With them, backorders max(N_k - S_k, 0) are integrated exactly like
    the queues: trajectories "backorders_by_skill" / "backorders_total", phase means and peaks, and a second recovery
    measure "recovery_backorders" on the backorder trajectory (same rule as for the queue).
    preemptive=False: non-preemptive priorities (no interruptions; a part returned by an absent technician waits).
    switch: None, or dict(costs=[M, N] cost matrix of the rule used during the switch window (as skillServerCosts;
    None = FCFS), preemptive=bool, start=..., end=...) with start/end in EXPECTED FAILURES: on [start, end) the shop
    dispatches by that rule and discipline instead of the base ones (operational response to a disruption). Defaults
    leave the random stream and the results unchanged."""
    rate, cdf, rates, costs, scores, buckets = ss._validate_model(
        requestArrivalRate, skillDistribution, skillServerRates, skillServerCosts, histogramBucketsInput)
    maxQueue = ss._integer(maxQueue, "maxQueue", 1)
    schedule = ss.make_surge_schedule(rate, expectedTotalNumberRequests, numberWarmingUpRequests,
                                      numberBaselineRequests, numberSurgeRequests, surgeMultiplier,
                                      sampleEveryArrivals, queueReportEveryArrivals=queueReportEveryArrivals)
    ss._validate_recovery_options(recoveryAbsTolerance, recoveryRelTolerance, recoveryHoldArrivals)
    n_servers, n_skills = rates.shape
    lam = rate * np.diff(np.r_[0.0, cdf])
    use_S = stocks is not None
    S = np.zeros(n_skills, np.int64) if stocks is None else np.asarray(stocks, np.int64)
    if S.shape != (n_skills,) or np.any(S < 0):
        raise ValueError("stocks must be a nonnegative integer vector with one entry per SKU.")
    edges = schedule["bin_edges_x"] / rate                     # physical time
    phase_edges = schedule["phase_edges_x"] / rate
    expected_in_queue = lam.max() / rate * expectedTotalNumberRequests * max(1.0, float(surgeMultiplier))
    cap = int(1.3 * expected_in_queue) + 2000
    if absence is None:
        abs_j, abs_t0, abs_t1 = -1, _INF, _INF
    else:
        abs_j, a0, a1 = absence
        if not (0 <= abs_j < n_servers) or not (0 <= a0 < a1):
            raise ValueError("absence must be (technician, start, end) with 0 <= start < end, in expected failures")
        abs_t0, abs_t1 = a0 / rate, a1 / rate
    if switch is None:
        scores2, pre2, sw_t0, sw_t1 = scores, bool(preemptive), _INF, _INF
    else:
        c2 = switch.get("costs")
        c2 = rates.copy() if c2 is None else np.asarray(c2, float)              # FCFS: equal score (cost / rate = 1)
        scores2 = ss._validate_model(requestArrivalRate, skillDistribution, skillServerRates, c2, histogramBucketsInput)[4]
        pre2 = bool(switch.get("preemptive", True)); sw_t0, sw_t1 = float(switch["start"]) / rate, float(switch.get("end", np.inf)) / rate
    (bin_q, bin_sys, bin_bo, bin_arr, bin_dep, phase_q, phase_sys, phase_bo, phase_busy, phase_dur, peak_q, peak_bo,
     arrivals, departures, completed, comp_post, dist, over, count, qlen, in_service, overflow_queue, n_events,
     n_preempt, n_absence_events) = _run_surge(lam, rates, scores, edges, schedule["bin_phases"].astype(np.int64), phase_edges,
                             float(surgeMultiplier), S, use_S, int(seed), maxQueue, cap, abs_j, abs_t0, abs_t1,
                             scores2, bool(preemptive), pre2, sw_t0, sw_t1)
    if overflow_queue:
        raise RuntimeError("queue capacity exceeded")
    durations = np.diff(phase_edges)
    if not np.allclose(phase_dur, durations, rtol=1e-9, atol=1e-8):
        raise RuntimeError("Observation windows were not fully integrated.")
    if not np.array_equal(arrivals.sum(axis=0) - departures.sum(axis=0), count):
        raise RuntimeError("Arrival/departure conservation failed.")
    if not np.array_equal(count, qlen + in_service):
        raise RuntimeError("Queue/service conservation failed.")

    bin_dur = np.diff(edges)
    queue_curve = bin_q / bin_dur[:, None]
    system_curve = bin_sys / bin_dur[:, None]
    bo_curve = bin_bo / bin_dur[:, None]
    phase_queue = ss._divide(phase_q, durations[:, None])
    baseline = phase_queue[1].copy()
    observation = phase_edges[4] - phase_edges[1]
    phases = {}
    for p, name in enumerate(ss.PHASES):
        phases[name] = {
            "expected_arrivals": schedule["expected_arrivals"][p], "duration": durations[p],
            "normalized_duration": durations[p] * rate,
            "actual_arrivals_by_skill": arrivals[p].copy(), "departures_by_skill": departures[p].copy(),
            "arrival_cohort_completed_by_skill": completed[p].copy(),
            "unfinished_arrival_cohort_by_skill": arrivals[p] - completed[p],
            "mean_queue_by_skill": phase_queue[p].copy(), "mean_queue_total": float(phase_queue[p].sum()),
            "mean_number_in_system_by_skill": ss._divide(phase_sys[p], durations[p]),
            "max_queue_total": int(peak_q[p]), "utilization": ss._divide(phase_busy[p], durations[p]),
            "mean_backorders_by_skill": ss._divide(phase_bo[p], durations[p]) if use_S else None,
            "mean_backorders_total": float(ss._divide(phase_bo[p].sum(), durations[p])) if use_S else None,
            "max_backorders_total": int(peak_bo[p]) if use_S else None,
            "waiting": None,
        }
    # Report windows (queue_reports) in the units of the Python engine: bin areas in x = rate * t.
    result = {
        "schedule": schedule,
        "model": {"base_rate": rate, "n_servers": n_servers, "n_skills": n_skills, "service_rates": rates,
                  "skill_cdf": cdf, "costs": costs, "priority_scores": scores, "preemptive": bool(preemptive), "switch": None if switch is None else {k: v for k, v in switch.items() if k != "costs"},
                  "engine": "surge_fast (compiled; rules of simulation_fast)", "stocks": S if use_S else None},
        "seed": {"entropy": int(seed), "spawn_key": ()},
        "normalized_time": schedule["normalized_time"].copy(),
        "normalized_time_edges": schedule["normalized_time_edges"].copy(),
        "time": (edges[:-1] + bin_dur / 2),
        "queue_by_skill": queue_curve, "queue_total": queue_curve.sum(axis=1),
        "number_in_system_by_skill": system_curve,
        "queue_excess_by_skill": queue_curve - baseline, "queue_excess_total": queue_curve.sum(axis=1) - baseline.sum(),
        "baseline_queue_by_skill": baseline, "baseline_queue_total": float(baseline.sum()),
        "bin_arrivals_by_skill": bin_arr, "bin_departures_by_skill": bin_dep,
        "phases": phases,
        "queue_reports": ss._queue_report_metrics(schedule, bin_q * rate, bin_arr, baseline),
        "recovery": ss.measure_recovery(schedule, queue_curve.sum(axis=1), float(baseline.sum()),
                                        recoveryAbsTolerance=recoveryAbsTolerance,
                                        recoveryRelTolerance=recoveryRelTolerance,
                                        recoveryHoldArrivals=recoveryHoldArrivals),
        "number_in_system_pmf": dist / observation, "number_in_system_overflow": over / observation,
        "utilization": phase_busy[1:].sum(axis=0) / observation,
        "assignment_fractions": ss._divide(comp_post, comp_post.sum(axis=0)),
        "waiting": None,
        "diagnostics": {"actual_arrivals": int(arrivals.sum()), "actual_departures": int(departures.sum()),
                        "unfinished_by_skill": count.copy(), "final_queue_by_skill": qlen.copy(),
                        "final_in_service_by_skill": in_service, "processed_events": int(n_events),
                        "preemptions": int(n_preempt), "absence_events": int(n_absence_events)},
        "absence": None if absence is None else {"technician": int(abs_j), "start": float(a0), "end": float(a1)},
    }
    if use_S:
        bo_base = float(phase_bo[1].sum() / durations[1])
        result.update({
            "backorders_by_skill": bo_curve, "backorders_total": bo_curve.sum(axis=1),
            "baseline_backorders_total": bo_base,
            "recovery_backorders": ss.measure_recovery(schedule, bo_curve.sum(axis=1), bo_base,
                                                       recoveryAbsTolerance=recoveryAbsTolerance,
                                                       recoveryRelTolerance=recoveryRelTolerance,
                                                       recoveryHoldArrivals=recoveryHoldArrivals),
        })
    return result


def simulation_batch_run(
    failureRates, serviceRates, skillServerAssignment, priorities=None, histogramBucketsInput=(0.0,),
    expectedTotalNumberRequests=100_000, numberWarmingUpRequests=10_000, replications=35, maxQueue=500,
    nCores=None, startSeed=10, *,
    numberBaselineRequests=20_000, numberSurgeRequests=10_000, surgeMultiplier=3.0, sampleEveryArrivals=100.0,
    queueReportEveryArrivals=10_000.0, recoveryAbsTolerance=1.0, recoveryRelTolerance=0.10,
    recoveryHoldArrivals=1_000.0, preemptive=True, collectWaitingTimeStatisticsInput=False, caseId=0,
    mpStartMethod=None, keepReplicationResults=False, stocks=None, absence=None, switch=None, switch_priorities=None,
):
    """Replications run serially (nCores and mpStartMethod are ignored: a replication takes well under a second).
    Replication i uses seed startSeed + 20 i; caseId is recorded only -- give each case its own startSeed.
    Same result keys as surge_simulation.simulation_batch_run, plus backorder summaries when stocks are given."""
    failures = np.asarray(failureRates, dtype=float)
    assignment = np.asarray(skillServerAssignment, dtype=float)
    base_rate = ss._positive_float(failures.sum(), "sum(failureRates)")
    service = np.asarray(serviceRates, dtype=float)
    rates = assignment * service
    priority = np.broadcast_to(1.0 if priorities is None else np.asarray(priorities, dtype=float), rates.shape)
    costs = rates * priority
    cdf = np.cumsum(failures / base_rate)
    cdf[-1] = 1.0
    reps = ss._integer(replications, "replications", 1)
    startSeed = ss._integer(startSeed, "startSeed")
    shared = dict(requestArrivalRate=base_rate, skillDistribution=cdf, skillServerRates=rates, skillServerCosts=costs,
                  histogramBucketsInput=histogramBucketsInput, expectedTotalNumberRequests=expectedTotalNumberRequests,
                  numberWarmingUpRequests=numberWarmingUpRequests, numberBaselineRequests=numberBaselineRequests,
                  numberSurgeRequests=numberSurgeRequests, surgeMultiplier=surgeMultiplier,
                  sampleEveryArrivals=sampleEveryArrivals, maxQueue=maxQueue, preemptive=preemptive,
                  queueReportEveryArrivals=queueReportEveryArrivals, recoveryAbsTolerance=recoveryAbsTolerance,
                  recoveryRelTolerance=recoveryRelTolerance, recoveryHoldArrivals=recoveryHoldArrivals, stocks=stocks, absence=absence,
                  switch=None if switch is None else dict(switch, costs=None if switch_priorities is None else rates * np.broadcast_to(np.asarray(switch_priorities, float), rates.shape)))
    runs = [simulation(**shared, seed=startSeed + 20 * i) for i in range(reps)]
    R = ss._replication_summary
    trajectory_keys = ("queue_total", "queue_by_skill", "number_in_system_by_skill", "queue_excess_total",
                       "queue_excess_by_skill", "bin_arrivals_by_skill", "bin_departures_by_skill")
    phase_keys = ("actual_arrivals_by_skill", "departures_by_skill", "arrival_cohort_completed_by_skill",
                  "unfinished_arrival_cohort_by_skill", "mean_queue_total", "mean_queue_by_skill",
                  "mean_number_in_system_by_skill", "max_queue_total", "utilization")
    if stocks is not None:
        trajectory_keys += ("backorders_total", "backorders_by_skill")
        phase_keys += ("mean_backorders_total", "mean_backorders_by_skill", "max_backorders_total")
    result = {
        "schedule": runs[0]["schedule"], "model": runs[0]["model"],
        "replications": reps, "start_seed": startSeed, "case_id": caseId,
        "seeds": [startSeed + 20 * i for i in range(reps)],
        "normalized_time": runs[0]["normalized_time"], "normalized_time_edges": runs[0]["normalized_time_edges"],
        "trajectories": {key: R([r[key] for r in runs]) for key in trajectory_keys},
        "baseline": {"queue_total": R([r["baseline_queue_total"] for r in runs]),
                     "queue_by_skill": R([r["baseline_queue_by_skill"] for r in runs])},
        "phases": {name: {key: R([r["phases"][name][key] for r in runs]) for key in phase_keys} for name in ss.PHASES},
        "queue_reports": {"windows": runs[0]["queue_reports"]["windows"],
                          **{key: R([r["queue_reports"][key] for r in runs])
                             for key in ("mean_queue_total", "mean_queue_by_skill", "mean_queue_excess_total",
                                         "mean_queue_excess_by_skill", "actual_arrivals_total",
                                         "actual_arrivals_by_skill")}},
        "recovery": ss._summarize_recovery([r["recovery"] for r in runs]),
        "replication_diagnostics": [r["diagnostics"] for r in runs],
        "replication_waiting_statistics": [None for _ in runs],
        "phase_waiting_statistics": {name: [None for _ in runs] for name in ss.PHASES},
    }
    if stocks is not None:
        result["baseline"]["backorders_total"] = R([r["baseline_backorders_total"] for r in runs])
        result["recovery_backorders"] = ss._summarize_recovery([r["recovery_backorders"] for r in runs])
    for key in ("number_in_system_pmf", "number_in_system_overflow", "utilization", "assignment_fractions"):
        result[key] = R([r[key] for r in runs])
    if keepReplicationResults:
        result["raw_replications"] = runs
    return result
